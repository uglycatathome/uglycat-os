# stage0「提取」专属提示（不进 stage1 解码块，避免指令与职责错配）
EXTRACT_HINT = "任务提示：提取时优先抓政策表述、强调词与措辞强度，忽略与政策无关的普通叙述。"


def _grading_block() -> str:
    """措辞分级部分（动词链 + 高频词分级表 + 力度分级），stage0/stage1 共用。"""
    lines = [VERB_LADDER, "", "## 高频词分级（哪些是强措辞）"]
    lines += [f"- {level}：{words} → {subtext}" for level, words, subtext in INTENSITY_TABLE]
    if INTENSITY_GRADING:
        lines += ["", "## 力度分级"] + [f"- {g}" for g in INTENSITY_GRADING]
    return "\n".join(lines)


def stage0_block() -> str:
    """stage0「提取」用：只给「哪些词是强措辞」，帮模型聚焦政策表述与强调词。"""
    return _grading_block() + "\n\n" + EXTRACT_HINT


def stage1_block() -> str:
    """stage1「解码」用：全量（公式 + 分级 + 7 张专题表 + 政策术语 + 反向读 + 误读规避）。"""
    parts = [DECODE_FORMULA, _grading_block()]
    parts.append("## 经济类专题表（官方表述 → 潜台词）")
    for name, rows in TOPIC_TABLES.items():
        parts.append(f"### {name}")
        parts += [f"- {a} → {b}" for a, b in rows]
    if POLICY_TERMS:
        parts.append("## 政策术语对照")
        parts += [f"- {k} → {v}" for k, v in POLICY_TERMS.items()]
    parts.append(REVERSE_READING)
    if MISREAD_WARNINGS:
        parts.append("## 误读规避\n" + "\n".join(f"- {w}" for w in MISREAD_WARNINGS))
    return "\n\n".join(parts)


def stage2_block() -> str:
    """stage2「历史对比」用：公式 + 跨期对照原则 + 术语演变参照（不给专题表）。"""
    parts = [DECODE_FORMULA, PERIOD_COMPARE]
    if TERM_EVOLUTION:
        parts.append("## 术语演变参照\n" + "\n".join(f"- {t}" for t in TERM_EVOLUTION))
    return "\n\n".join(parts)


def stage3_block() -> str:
    """stage3「建议」不注入方法论：它只消费 stage1/stage2 的成品。"""
    return ""
