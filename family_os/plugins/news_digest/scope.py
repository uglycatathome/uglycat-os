def label(category: str | None) -> str:
    """类别 key → 展示名（未知/空返回空串）。"""
    return CATEGORY_LABELS.get(category or "", "")


def _target_meeting(title: str) -> bool:
    return any(re.search(p, title or "") for p in _TARGET_MEETING_RES)


def _industry_event(title: str) -> bool:
    """全国性/国际性产业大会（展示型）；会前预告与筹备稿不算。"""
    if _EVENT_PREVIEW_RE.search(title or ""):
        return False
    return any(re.search(p, title or "") for p in _INDUSTRY_EVENT_RES)


def _policy_doc(title: str, text: str) -> bool:
    """正式文件词 + 国家级发布主体（主体可在摘要里，如「发改委公布《…办法》」）。"""
    if not any(w in title for w in _DOC_WORDS):
        return False
    return bool(_NATIONAL_BODY_RE.search(text))


def classify(title: str, summary: str = "") -> str | None:
    """判断一条新闻是否在选题范围内，返回类别 key；不在范围返回 None。

    顺序很关键：
      ① 国家级重要会议优先（「政治局召开会议审议巡视报告」不能被纪检词误杀）；
      ② 头部产业大会（展示型，单列类别，先于活动排除判断）；
      ③ 党务/反腐/理论 → 排除；
      ④ 个人署名、上表之外的活动、媒体栏目 → 排除；
      ⑤ 地方/城市信息（除非标题含全国性主体）→ 排除；
      ⑥ 央行技术性操作（无利率决策）→ 排除；
      ⑦ 正式文件 → policy_doc；利率决策/全国经济数据 → indicator；
      ⑧ 其余一律不算（含「出口额/进出口金额」这类数量新闻）。
    """
    title = " ".join((title or "").split())
    if not title:
        return None
    text = f"{title} {' '.join((summary or '').split())}"

    if _target_meeting(title):
        return MEETING
    if _industry_event(title):
        return INDUSTRY_EVENT
    if _EXCLUDED_RE.search(title):
        return None
    if _MEDIA_COLUMN_RE.search(title):
        return None
    m = _QUOTE_TITLE_RE.match(title)
    if m and not any(t in m.group(1) for t in _ORG_PREFIX_TOKENS):
        return None
    if _EVENT_RE.search(text):
        return None
    if _LOCAL_RE.search(title) and not _NATIONAL_ACTOR_RE.search(title):
        return None
    if _ACTIVITY_RE.search(title):
        return None
    if _MONETARY_OP_RE.search(title) and not _RATE_RE.search(text):
        return None
    if _policy_doc(title, text):
        return POLICY_DOC
    if _RATE_RE.search(title):
        return INDICATOR
    if _DATA_RE.search(title):
        return INDICATOR
    # 标题只写「发布国民经济运行情况」这类概括、指标名在摘要里：
    # 只要标题里有官方发布主体，就按摘要里的指标认定（如「国家统计局发布…GDP」）。
    if _NATIONAL_BODY_RE.search(title) and _DATA_RE.search(text):
        return INDICATOR
    return None
